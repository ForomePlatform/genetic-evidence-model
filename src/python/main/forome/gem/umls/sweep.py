def _build_client(provider: str, dsn: str | None = None):
    if provider == "pg":
        # the local PostgreSQL index (forome.gem.umls.local_umls); the exact
        # UMLS release comes from its umls_release row
        from forome.gem.umls.local_umls import PgUMLSClient
        return PgUMLSClient(dsn)
    if provider == "null":
        from forome.gem.umls.uts_client import NullClient
        return NullClient()
    if provider == "uts":
        # Lazy: adjudicate_ui.api_key() reads UMLS_API_KEY or the repo .envrc.
        # The key is passed to the client only; it is never printed or logged.
        from forome.gem.umls import adjudicate_ui as UI
        from forome.gem.umls import build_umls_crosswalk as H
        from forome.gem.umls.uts_client import UTSClient
        key = UI.api_key()
        if not key:
            raise SystemExit("gem-umls-sweep: no UMLS API key found (set "
                             "UMLS_API_KEY or add it to .envrc); use "
                             "--provider null for a dry run.")
        return UTSClient(key, cache_dir=H.CACHE_DIR)
    raise SystemExit(f"gem-umls-sweep: unknown provider '{provider}'")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        prog="gem-umls-sweep", description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("protocol", help="pre-registered protocol YAML")
    ap.add_argument("--out", help="results YAML (default: "
                    "data/umls/sweeps/<name>.results.yaml)")
    ap.add_argument("--tex", help="also write an S2-style LaTeX longtable here")
    ap.add_argument("--dsn", default=None,
                    help="PostgreSQL DSN for --provider pg (default: $GEM_UMLS_DSN, "
                         "else postgresql:///umls)")
    ap.add_argument("--provider", choices=["uts", "pg", "null"], default="uts",
                    help="uts = live UTS REST with disk cache (default); "
                         "null = no results, for a dry run")
    ap.add_argument("--enrich", action="store_true",
                    help="fetch each candidate's atoms to list its English SABs")
    ap.add_argument("--limit-per-query", type=int, default=None, metavar="N",
                    help="keep at most N hits per query")
    ap.add_argument("--umls-release", default=None, metavar="LABEL",
                    help="label for the UMLS release queried (e.g. 2025AA); "
                         "default: the client's version string")
    args = ap.parse_args(argv)

    try:
        protocol = load_protocol(args.protocol)
    except ProtocolError as e:
        print(f"gem-umls-sweep: invalid protocol: {e}", file=sys.stderr)
        return 2

    out_path = Path(args.out) if args.out else (
        SWEEPS_DIR / f"{protocol['name']}.results.yaml")
    client = _build_client(args.provider, args.dsn)
    results = run(protocol, client, enrich=args.enrich,
                  limit_per_query=args.limit_per_query, umls=args.umls_release)
    previous = load_results(out_path)
    results = merge_curation(results, previous)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(dump_results(results))
    s = results["summary"]
    print(f"Wrote {out_path}: {s['n_queries']} queries, {s['n_candidates']} "
          f"candidates" + (f", {s['n_carried_over']} curated entries carried over"
                           if previous else "")
          + (f", {s['n_stale_curation']} stale" if s.get("n_stale_curation") else ""))
    for p in results["passes"]:
        if p["status"] != "executed":
            print(f"  pass '{p['name']}' skipped: {p.get('reason')}")
    if args.tex:
        tex_path = Path(args.tex)
        tex_path.parent.mkdir(parents=True, exist_ok=True)
        tex_path.write_text(render_tex(results))
        print(f"Wrote {tex_path}")
    return 0


